    function tickCountdown() {
      if (remainingSeconds > 0) {
        remainingSeconds--;
        const d = Math.floor(remainingSeconds / (3600 * 24));
        const h = Math.floor((remainingSeconds % (3600 * 24)) / 3600);
        const m = Math.floor((remainingSeconds % 3600) / 60);
