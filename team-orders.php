          b.classList.add('bg-surface-container-high', 'text-on-surface');
        });
        btn.classList.remove('bg-surface-container-high', 'text-on-surface');
        btn.classList.add('bg-primary-container', 'text-on-primary-container');
        
        state.sportName = btn.getAttribute('data-sport-name');
        
        // Also update the form dropdown default if possible
        const formSport = document.getElementById('form-sport');
        if (formSport) {
          const matchingOption = Array.from(formSport.options).find(opt => 
            opt.text.toLowerCase().includes(btn.getAttribute('data-sport').toLowerCase())
          );
          if (matchingOption) formSport.value = matchingOption.value;
        }

        updateQuote();
      });
    });

    // Package Tier Cards
    const packageCards = document.querySelectorAll('.package-card');
    packageCards.forEach(card => {
      card.addEventListener('click', () => {
        packageCards.forEach(c => {
          c.classList.remove('bg-surface-container-highest', 'shadow-lg');
          c.classList.add('bg-surface-container-high');
          const indicator = c.querySelector('.tier-indicator');
          if (indicator) {
            indicator.className = 'w-4 h-4 rounded-full bg-outline-variant flex items-center justify-center tier-indicator';
            indicator.innerHTML = '';
          }
        });

        card.classList.remove('bg-surface-container-high');
        card.classList.add('bg-surface-container-highest', 'shadow-lg');
        
        const activeIndicator = card.querySelector('.tier-indicator');
        if (activeIndicator) {
          activeIndicator.className = 'w-4 h-4 rounded-full bg-primary-container flex items-center justify-center tier-indicator';
          activeIndicator.innerHTML = '<span class="w-2 h-2 rounded-full bg-on-primary-container"></span>';
        }

        state.tierKey = card.getAttribute('data-tier');
        state.basePrice = parseInt(card.getAttribute('data-base-price'), 10);
        updateQuote();
      });
    });

    // Quantity Slider
    const qtySlider = document.getElementById('quantity-slider');
    qtySlider.addEventListener('input', (e) => {
      state.quantity = parseInt(e.target.value, 10);
      const formQty = document.getElementById('form-quantity');
      if (formQty) formQty.value = state.quantity;
      updateQuote();
    });

    // Checkbox Addons
    const sponsorCheck = document.getElementById('addon-sponsors');
    const badgeCheck = document.getElementById('addon-badge');
    
    sponsorCheck.addEventListener('change', (e) => {
      state.addonSponsors = e.target.checked;
      updateQuote();
    });

    badgeCheck.addEventListener('change', (e) => {
      state.addonBadge = e.target.checked;
      updateQuote();
    });

