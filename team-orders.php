    downloadBtn.addEventListener('click', () => {
      const originalText = downloadBtn.innerHTML;
      downloadBtn.innerHTML = '<span class="material-symbols-outlined text-[18px] animate-spin">refresh</span> Generating Official PDF...';
      setTimeout(() => {
        downloadBtn.innerHTML = '<span class="material-symbols-outlined text-[18px] text-secondary-fixed">check_circle</span> Quotation Ready! Downloading...';
        setTimeout(() => {
          downloadBtn.innerHTML = originalText;
