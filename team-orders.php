  (function() {
    // Pricing Config & State
    const state = {
      sportName: 'Cricket Match & Whites',
      tierKey: 'pro',
      basePrice: 4950,
      quantity: 25,
      addonSponsors: false,
      addonBadge: false
    };

    const tiers = {
      basic: { name: 'Match Day Basic', price: 3200 },
      pro: { name: 'Pro Team Pack', price: 4950 },
      championship: { name: 'Championship Bundle', price: 9800 }
    };

    function calculateDiscount(qty) {
      if (qty >= 250) return { pct: 35, label: 'National Tier (35% Factory Rebate)' };
      if (qty >= 100) return { pct: 25, label: 'Franchise Tier (25% Factory Rebate)' };
      if (qty >= 50) return { pct: 18, label: 'Academy Tier (18% Factory Rebate)' };
      if (qty >= 20) return { pct: 10, label: 'Club Tier (10% Factory Rebate)' };
      return { pct: 0, label: 'Standard Team Rate (0% Rebate)' };
    }

    function formatLKR(amount) {
      return 'LKR ' + Math.round(amount).toLocaleString('en-US');
    }

    function updateQuote() {
      // Elements
      const sportLabel = document.getElementById('selected-sport-label');
      const qtyDisplay = document.getElementById('quantity-display');
      const discountText = document.getElementById('discount-status-text');
      const discountBadge = document.getElementById('discount-badge');
      
      const ledgerSport = document.getElementById('ledger-sport');
      const ledgerTier = document.getElementById('ledger-tier');
      const ledgerBasePrice = document.getElementById('ledger-base-price');
      const ledgerAddons = document.getElementById('ledger-addons');
      const ledgerQuantity = document.getElementById('ledger-quantity');
      const ledgerSubtotal = document.getElementById('ledger-subtotal');
      const ledgerSavings = document.getElementById('ledger-savings');
      const ledgerGrandTotal = document.getElementById('ledger-grand-total');
      const ledgerEffectiveUnit = document.getElementById('ledger-effective-unit');

      // Calculate Addons
      let addonsPerUnit = 0;
      if (state.addonSponsors) addonsPerUnit += 250;
      if (state.addonBadge) addonsPerUnit += 400;

      const unitCost = state.basePrice + addonsPerUnit;
      const grossTotal = unitCost * state.quantity;
      const discount = calculateDiscount(state.quantity);
      const savingsAmount = grossTotal * (discount.pct / 100);
      const grandTotal = grossTotal - savingsAmount;
      const effectivePerPlayer = grandTotal / state.quantity;

      // Update Ledger
      sportLabel.textContent = state.sportName.toUpperCase() + ' SELECTED';
      qtyDisplay.textContent = state.quantity;
      discountText.textContent = discount.label;
      discountBadge.textContent = discount.pct > 0 ? (discount.pct + '% OFF') : 'TIER 1';

      ledgerSport.textContent = state.sportName;
      ledgerTier.textContent = tiers[state.tierKey].name;
      ledgerBasePrice.textContent = formatLKR(state.basePrice);
      ledgerAddons.textContent = addonsPerUnit > 0 ? formatLKR(addonsPerUnit) + ' / unit' : 'LKR 0';
      ledgerQuantity.textContent = state.quantity + ' sets';
      
      ledgerSubtotal.textContent = formatLKR(grossTotal);
      ledgerSavings.textContent = '- ' + formatLKR(savingsAmount);
      ledgerGrandTotal.textContent = formatLKR(grandTotal);
      ledgerEffectiveUnit.textContent = formatLKR(effectivePerPlayer) + ' / player';
    }

